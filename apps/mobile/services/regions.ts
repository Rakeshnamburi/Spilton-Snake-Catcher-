export function isTargetState(value: string): value is TargetState {
  return Object.prototype.hasOwnProperty.call(TARGET_REGIONS, value);
}

export function coordinatesAreInState(state: TargetState, latitude: number, longitude: number) {
  const bounds = STATE_BOUNDS[state];
  return latitude >= bounds.south && latitude <= bounds.north
    && longitude >= bounds.west && longitude <= bounds.east;
}

